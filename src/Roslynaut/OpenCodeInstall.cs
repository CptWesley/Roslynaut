using System.Text.Json;
using System.Text.Json.Nodes;

namespace Roslynaut;

/// <summary>
/// Registers the server with OpenCode for all projects (<c>--install opencode</c>), along with a plugin that points OpenCode to the server's
/// tools when it reads or greps C# files. The plugin only adds that suggestion: it never blocks or approves a tool call.
/// </summary>
internal static class OpenCodeInstall
{
    public const string HookOption = "--opencode-hook";
    private const string Name = "roslynaut";

    // Marks the plugin as ours, so a file that a user wrote is left alone.
    private const string Marker = "// roslynaut: generated by `roslynaut --install opencode`";

    public static void Run(bool uninstall)
    {
        var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        // XDG_CONFIG_HOME moves OpenCode's global configuration, as it does for OpenCode itself.
        var configDir = Environment.GetEnvironmentVariable("XDG_CONFIG_HOME") is { Length: > 0 } dir
            ? Path.Combine(dir, "opencode")
            : Path.Combine(home, ".config", "opencode");
        // OpenCode reads either file; keep the one it already has.
        var configFile = new[] { "opencode.jsonc", "opencode.json" }
            .Select(name => Path.Combine(configDir, name))
            .FirstOrDefault(File.Exists) ?? Path.Combine(configDir, "opencode.json");
        var pluginFile = Path.Combine(configDir, "plugins", "roslynaut.js");
        if (uninstall)
        {
            Uninstall(configFile, pluginFile, Console.Out);
            return;
        }

        Install(configFile, pluginFile, AgentInstall.Command(), Console.Out);
    }

    internal static void Install(string configFile, string pluginFile, string[] command, TextWriter log)
    {
        var config = JsonFile.Read(configFile);
        var servers = ((config["mcp"] ??= new JsonObject())["servers"] ??= new JsonObject()).AsObject();
        var server = new JsonObject { ["type"] = "local", ["command"] = JsonFile.Strings(command) };
        var found = Servers(servers);
        if (found is [{ Key: Name, Value: var value }] && JsonNode.DeepEquals(value, server))
            log.WriteLine($"The MCP server {Name} in {configFile} is up to date.");
        else
        {
            foreach (var entry in found)
                servers.Remove(entry.Key);
            servers[Name] = server;
            JsonFile.Write(configFile, config);
            log.WriteLine($"{(found is [] ? "Added" : "Updated")} the MCP server {Name} in {configFile}.");
        }

        var plugin = Plugin(command);
        var existing = File.Exists(pluginFile) ? File.ReadAllText(pluginFile) : null;
        if (existing == plugin)
            log.WriteLine($"The Roslynaut plugin in {pluginFile} is up to date.");
        else if (existing is not null && !existing.StartsWith(Marker, StringComparison.Ordinal))
            log.WriteLine($"Left the plugin {pluginFile} alone, as Roslynaut did not write it.");
        else
        {
            Directory.CreateDirectory(Path.GetDirectoryName(pluginFile)!);
            File.WriteAllText(pluginFile, plugin);
            log.WriteLine(
                $"{(existing is null ? "Added" : "Updated")} the Roslynaut plugin, which suggests its tools when OpenCode reads or greps C# files, "
                + $"in {pluginFile}.");
        }
    }

    /// <summary>
    /// Removes what <see cref="Install"/> adds, by any version, before the tool is uninstalled: else OpenCode fails to start the plugin on
    /// every read and grep.
    /// </summary>
    internal static void Uninstall(string configFile, string pluginFile, TextWriter log)
    {
        var config = JsonFile.Read(configFile);
        if (config["mcp"]?["servers"] is JsonObject servers && Servers(servers) is [_, ..] found)
        {
            foreach (var entry in found)
                servers.Remove(entry.Key);
            JsonFile.Write(configFile, config);
            log.WriteLine($"Removed the MCP server {Name} from {configFile}.");
        }
        else
            log.WriteLine($"There is no MCP server {Name} in {configFile}.");

        if (File.Exists(pluginFile) && File.ReadAllText(pluginFile).StartsWith(Marker, StringComparison.Ordinal))
        {
            File.Delete(pluginFile);
            log.WriteLine($"Removed the Roslynaut plugin from {pluginFile}.");
        }
        else
            log.WriteLine($"There is no Roslynaut plugin in {pluginFile}.");
    }

    // Whatever the case of its name, as OpenCode would read both.
    private static List<KeyValuePair<string, JsonNode?>> Servers(JsonObject servers) =>
        [.. servers.Where(entry => entry.Key.Equals(Name, StringComparison.OrdinalIgnoreCase))];

    /// <summary>The plugin: OpenCode passes the tool call on stdin and takes the suggestion from stdout.</summary>
    public static int Hook()
    {
        if (ClaudeInstall.Context(JsonNode.Parse(Console.OpenStandardInput())) is { } context)
            Console.Out.Write(context);
        return 0;
    }

    internal static string Plugin(string[] command) => $$"""
        {{Marker}}
        // It asks the server for a suggestion after OpenCode reads or greps C# files, and appends it to the tool result.
        import { spawn } from "node:child_process";

        const COMMAND = [{{string.Join(", ", command.Select(part => JsonSerializer.Serialize(part)))}}];
        const OPTION = "{{HookOption}}";

        function hint(call) {
          return new Promise((resolve) => {
            let text = "";
            try {
              const child = spawn(COMMAND[0], [...COMMAND.slice(1), OPTION], {
                stdio: ["pipe", "pipe", "ignore"],
                windowsHide: true,
              });
              child.on("error", () => resolve(""));
              child.stdout.setEncoding("utf8");
              child.stdout.on("data", (chunk) => { text += chunk; });
              child.on("close", () => resolve(text));
              child.stdin.on("error", () => {});
              child.stdin.end(JSON.stringify(call));
            } catch {
              resolve("");
            }
          });
        }

        function append(content, text) {
          const part = { type: "text", text };
          if (typeof content === "string") return [{ type: "text", text: content }, part];
          if (Array.isArray(content)) return [...content, part];
          return [part];
        }

        // OpenCode 1.
        const server = async () => ({
          "tool.execute.after": async (input, output) => {
            const text = await hint({ tool: input.tool, input: input.args });
            if (text) output.output = `${output.output}\n\n${text}`;
          },
        });

        // OpenCode 2.
        const setup = async (ctx) => {
          await ctx.tool.hook("execute.after", async (event) => {
            if (event.status !== "completed") return;
            const text = await hint({ tool: event.tool, input: event.input });
            if (text) event.result = { ...event.result, content: append(event.result.content, text) };
          });
        };

        export default { id: "roslynaut", server, setup };
        """;
}
