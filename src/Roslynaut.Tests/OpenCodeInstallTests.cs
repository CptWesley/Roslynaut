using System.Text.Json.Nodes;

namespace Roslynaut.Tests;

public class OpenCodeInstallTests
{
    [Test]
    public void Install_AddsServerAndPlugin_KeepingTheRest()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var (config, plugin) = (Path.Combine(dir, "opencode.jsonc"), Path.Combine(dir, "plugins", "roslynaut.js"));
        File.WriteAllText(config, """{ "model": "x", "mcp": { "servers": { "other": { "type": "local", "command": ["x"] } } } }""");
        try
        {
            OpenCodeInstall.Install(config, plugin, ["dotnet", "Roslynaut.dll"], TextWriter.Null);

            var written = JsonNode.Parse(File.ReadAllText(config))!;
            written["model"]!.GetValue<string>().Should().Be("x");
            written["mcp"]!["servers"]!.AsObject().Select(server => server.Key).Should().Equal("other", "roslynaut");
            written["mcp"]!["servers"]!["roslynaut"]!.ToJsonString().Should().Be("""{"type":"local","command":["dotnet","Roslynaut.dll"]}""");
            File.ReadAllText(plugin).Should()
                .StartWith("// roslynaut: generated")
                .And.Contain("--opencode-hook")
                .And.Contain("\"dotnet\"")
                .And.Contain("\"Roslynaut.dll\"")
                .And.Contain("export default");
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Test]
    public void Install_ReplacesAnOlderInstallation_ThenLeavesItAlone()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var (config, plugin) = (Path.Combine(dir, "opencode.json"), Path.Combine(dir, "plugins", "roslynaut.js"));
        File.WriteAllText(config, """{ "mcp": { "servers": { "other": { "type": "local", "command": ["x"] }, "Roslynaut": { "type": "local", "command": ["old"] } } } }""");
        Directory.CreateDirectory(Path.GetDirectoryName(plugin)!);
        File.WriteAllText(plugin, "// roslynaut: generated by `roslynaut --install opencode`\nold");
        try
        {
            OpenCodeInstall.Install(config, plugin, ["dotnet", "Roslynaut.dll"], TextWriter.Null);
            var again = new StringWriter();
            OpenCodeInstall.Install(config, plugin, ["dotnet", "Roslynaut.dll"], again);

            JsonNode.Parse(File.ReadAllText(config))!["mcp"]!["servers"]!.ToJsonString().Should().Be(
                """{"other":{"type":"local","command":["x"]},"roslynaut":{"type":"local","command":["dotnet","Roslynaut.dll"]}}""");
            File.ReadAllText(plugin).Should().NotContain("old");
            again.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries).Should().AllSatisfy(line => line.Should().Contain("up to date"));
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Test]
    public void Install_LeavesAPluginItDidNotWriteAlone()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var (config, plugin) = (Path.Combine(dir, "opencode.json"), Path.Combine(dir, "plugins", "roslynaut.js"));
        Directory.CreateDirectory(Path.GetDirectoryName(plugin)!);
        File.WriteAllText(plugin, """export default { id: "mine" };""");
        try
        {
            OpenCodeInstall.Install(config, plugin, ["dotnet", "Roslynaut.dll"], TextWriter.Null);

            File.ReadAllText(plugin).Should().Be("""export default { id: "mine" };""");
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Test]
    public void Uninstall_RemovesServerAndPlugin_KeepingTheRest()
    {
        var dir = Directory.CreateTempSubdirectory().FullName;
        var (config, plugin) = (Path.Combine(dir, "opencode.json"), Path.Combine(dir, "plugins", "roslynaut.js"));
        File.WriteAllText(config, """{ "mcp": { "servers": { "other": { "type": "local", "command": ["x"] }, "Roslynaut": { "type": "local", "command": ["old"] } } } }""");
        try
        {
            OpenCodeInstall.Install(config, plugin, ["dotnet", "Roslynaut.dll"], TextWriter.Null);
            OpenCodeInstall.Uninstall(config, plugin, TextWriter.Null);
            var again = new StringWriter();
            OpenCodeInstall.Uninstall(config, plugin, again);

            JsonNode.Parse(File.ReadAllText(config))!["mcp"]!["servers"]!.ToJsonString().Should().Be("""{"other":{"type":"local","command":["x"]}}""");
            File.Exists(plugin).Should().BeFalse();
            again.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries).Should().AllSatisfy(line => line.Should().StartWith("There is no"));
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [TestCase("read", """{ "filePath": "C:/src/Program.cs" }""", true)]
    [TestCase("read", """{ "filePath": "C:/src/App.csproj" }""", false)]
    [TestCase("grep", """{ "pattern": "class", "include": "*.cs" }""", true)]
    [TestCase("grep", """{ "pattern": "class", "path": "docs" }""", false)]
    [TestCase("bash", """{ "command": "rg -t cs Submit" }""", true)]
    [TestCase("bash", """{ "command": "git add src/Program.cs" }""", false)]
    public void Hint_OnlyForCSharpFiles(string tool, string input, bool hints)
    {
        var hint = ClaudeInstall.Context(JsonNode.Parse($$"""{ "tool": "{{tool}}", "input": {{input}} }"""));

        if (hints)
            hint.Should().Contain("roslynaut");
        else
            hint.Should().BeNull();
    }
}
